import { chromium } from "@playwright/test";
const BASE = "http://localhost:5000";
const browser = await chromium.launch({ executablePath: process.env.REPLIT_PLAYWRIGHT_CHROMIUM_EXECUTABLE, args: ["--no-sandbox"] });
const page = await browser.newPage();
const EMAIL = `e2e-fullpay-${Date.now()}@vership.test`;
await page.goto(`${BASE}/prepacked-barrel`, { waitUntil: "networkidle" });
await page.locator("button, a").filter({ hasText: /order|choose|select/i }).first().click().catch(() => {});
await page.waitForTimeout(600);
await page.fill('input[name="firstName"]', "E2E");
await page.fill('input[name="lastName"]', "FullPay");
await page.fill('input[name="email"]', EMAIL);
await page.fill('input[name="phone"]', "4155550123");
await page.fill('input[name="recipient_name"]', "Test Recipient");
await page.fill('input[name="recipient_phone"]', "8765550123");
await page.fill('input[name="delivery_street"]', "1 Test Street");
await page.fill('input[name="delivery_town"]', "Kingston");
await page.selectOption('select[name="delivery_parish"]', "Kingston");
await page.click('form button[type="submit"]');
await page.waitForSelector("text=/complete payment/i", { timeout: 15000 });
// fill the Stripe PaymentElement (inside its iframe)
const frame = page.frameLocator('iframe[name^="__privateStripe"]').first();
await frame.locator('input[name="number"]').fill("4242424242424242", { timeout: 20000 });
await frame.locator('input[name="expiry"]').fill("12/30");
await frame.locator('input[name="cvc"]').fill("123");
const zip = frame.locator('input[name="postalCode"]');
if (await zip.count()) await zip.fill("33101");
await page.locator("button", { hasText: /^Pay \$/ }).click();
await page.waitForSelector("text=/your order is in/i", { timeout: 30000 });
const body = await page.textContent("body");
const orderId = (body.match(/ORD-PP-[\d-]+/) || [])[0];
console.log("confirmation shown, order:", orderId);
console.log(/Payment received/.test(body) ? "PASS — confirmation says payment received" : "FAIL — wrong copy");
await page.screenshot({ path: "/tmp/claude-1000/-home-runner-workspace/fae0fc25-8cd1-4387-8536-9e190ba93d7f/scratchpad/full-payment-confirmed.png", fullPage: true });
await browser.close();
console.log("ORDERID:" + orderId);
